
//1 
 const audio = document.getElementById("noteA1");
const bouton = document.getElementById("A1");

function activerSon1() {
    audio.currentTime = 0; 
    audio.play();
    bouton.classList.add('pressed');

    audio.onended = () => bouton.classList.remove('pressed');
    setTimeout(() => {
    bouton.classList.remove('pressed');
    }, 1000);
}

bouton.addEventListener('click', activerSon1);


